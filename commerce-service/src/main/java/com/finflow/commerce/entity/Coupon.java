
package com.finflow.commerce.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.Getter;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.Instant;

@Getter
@Entity
@Table(
        name = "coupons",
        uniqueConstraints = @UniqueConstraint(
                name = "uk_coupon_org_code",
                columnNames = {"organisation_id", "code"}
        )
)
public class Coupon {

    // Primary key generated by the database.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "coupon_id")
    private Long couponId;

    // Organisation that owns this coupon.
    @Column(name = "organisation_id", nullable = false)
    private Long organisationId;

    // Coupon code entered by the customer.
    @Column(nullable = false, length = 40)
    private String code;

    // Percentage discount.
    // Example: 10.00 means 10% off.
    @Column(name = "percent_off", nullable = false, precision = 5, scale = 2)
    private BigDecimal percentOff;

    // Whether the coupon can currently be used.
    @Column(name = "active", nullable = false)
    private boolean active;

    // Optional expiry timestamp.
    // Null means there is no configured expiry.
    @Column(name = "expires_at")
    private Instant expiresAt;

    // Required by JPA.
    protected Coupon() {
    }

    // Creates a coupon and normalises its code.
    public Coupon(Long organisationId, String code, BigDecimal percentOff, Instant expiresAt) {
        this.organisationId = organisationId;
        this.code = code.trim().toUpperCase();
        this.percentOff = percentOff;
        this.active = true;
        this.expiresAt = expiresAt;
    }

    // Applies the coupon percentage to a subtotal.
    public BigDecimal apply(BigDecimal subtotal) {

        // Inactive coupons cannot be applied.
        if (!active) {
            throw new IllegalStateException("Coupon inactive");
        }

        // Reject the coupon if its expiry time has passed.
        if (expiresAt != null && Instant.now().isAfter(expiresAt)) {
            throw new IllegalStateException("Coupon expired");
        }

        // Convert the percentage into a discount factor.
        // Example: 10% discount becomes 1 - 0.10 = 0.90.
        BigDecimal factor = BigDecimal.ONE.subtract(
                percentOff.divide(BigDecimal.valueOf(100), 4, RoundingMode.HALF_UP)
        );

        // Apply the factor and round the result to four decimal places.
        return subtotal.multiply(factor).setScale(4, RoundingMode.HALF_UP);
    }

    // Deactivates the coupon so it cannot be applied again.
    public void deactivate() {
        this.active = false;
    }
}
