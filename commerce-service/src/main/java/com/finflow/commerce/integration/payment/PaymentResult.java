
package com.finflow.commerce.integration.payment;

/**
 * Normalized payment-provider outcome.
 * Whether the result comes from a real wallet or a simulated adapter, the rest of Commerce Service receives this same structure.
 * walletId and walletTransactionId are populated when money actually moved.
 */
public record PaymentResult(
        PaymentOutcome outcome, // Final classification of the payment attempt.
        Long walletId, // Wallet involved in the transaction, when known.
        Long walletTransactionId, // Transaction ID generated by the wallet, when available.
        String failureCode // Provider or business failure code, when applicable.
) {

    /**
     * Creates an approved payment result.
     * @param walletId the wallet ID involved in the transaction.
     * @param walletTransactionId the transaction ID generated by the wallet.
     * @return a PaymentResult containing the payment result.
     */
    public static PaymentResult approved(
            Long walletId,
            Long walletTransactionId
    ) {
        return new PaymentResult(
                PaymentOutcome.APPROVED,
                walletId,
                walletTransactionId,
                null
        );
    }

    /**
     * Creates a declined payment result.
     * @param failureCode the provider or business failure code.
     * @return a PaymentResult containing the payment result.
     */
    public static PaymentResult declined(String failureCode) {
        return new PaymentResult(
                PaymentOutcome.DECLINED,
                null,
                null,
                failureCode
        );
    }

    /**
     * Creates an uncertain result.
     * This means we cannot confidently say whether payment succeeded.
     * @param failureCode the provider or business failure code.
     * @return the PaymentResult containing the payment result.
     */
    public static PaymentResult uncertain(String failureCode) {
        return new PaymentResult(
                PaymentOutcome.UNCERTAIN,
                null,
                null,
                failureCode
        );
    }

    /**
     * Creates a result for the simulated payment adapter.
     * @param outcome the payment outcome.
     * @return a PaymentResult containing the payment result.
     */
    public static PaymentResult simulated(PaymentOutcome outcome) {

        // If no sandbox outcome was provided, default to APPROVED.
        PaymentOutcome resolved = outcome == null
                ? PaymentOutcome.APPROVED
                : outcome;

        // Simulated payments do not provide real wallet transaction IDs.
        return new PaymentResult(resolved, null, null, null);
    }
}
